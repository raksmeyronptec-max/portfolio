export type IconName = keyof typeof paths;

export type IconProps = Omit<SVGProps<SVGSVGElement>, "name" | "children"> & {
  name: IconName;
  /** Rendered pixel size for both axes. */
  size?: number;
  /**
   * Accessible name. Omit for decorative icons (the default), which are hidden
   * from assistive technology.
   */
  label?: string;
};

export function Icon({ name, size = 20, label, className, ...rest }: IconProps) {
  const entry = paths[name];
  const isFilled = typeof entry === "object" && "fill" in entry;
  const node = isFilled ? entry.node : (entry as React.ReactNode);

  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill={isFilled ? "currentColor" : "none"}
      stroke={isFilled ? "none" : "currentColor"}
      strokeWidth={isFilled ? undefined : 1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cn("shrink-0", className)}
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
      {...rest}
    >
      {node}
    </svg>
  );
}

/** Names available at runtime, used by admin pickers for taxonomy icons. */
export const iconNames = Object.keys(paths) as IconName[];

/** Narrow an untrusted string (e.g. a CMS `icon` column) to a known icon. */
export function toIconName(value: string | null | undefined, fallback: IconName): IconName {
  if (value && value in paths) return value as IconName;
  return fallback;
}
